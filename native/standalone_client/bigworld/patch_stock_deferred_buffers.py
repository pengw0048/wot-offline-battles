#!/usr/bin/env python3
"""Attach the sampled depth and material conversion owner to the scene pipeline."""
import argparse
from pathlib import Path
import re


READER = '''// #1513 a556b0 loads the sky resource; a55970 publishes it on activation.
void EnviroMinder::loadStockDeferredMaterials(const DataSectionPtr& data, bool loadFromExternal)
{
    const BW::string resource = data->readString("skyGradientDome");
    DataSectionPtr source = (!resource.empty() && loadFromExternal) ?
        BWResource::openSection(resource) : data;
    loadStockDeferredMaterialSettings(source, stockDeferredMaterialSettings_);
    loadStockScreenSpaceShadowSettings(source, stockScreenSpaceShadowSettings_);
    if (s_activatedEM_ == this)
    {
        activateStockDeferredMaterialSettings(stockDeferredMaterialSettings_);
        activateStockScreenSpaceShadowSettings(stockScreenSpaceShadowSettings_);
    }
}

'''


def apply(root):
    root = Path(root)
    pending = {}

    def edit(relative, old, new, present=None):
        source = pending.get(relative)
        if source is None:
            source = (root / relative).read_text()
        if (present or new) in source:
            return
        if source.count(old) != 1:
            raise ValueError('Deferred scene owner anchor changed: ' + relative + ': ' + repr(old))
        pending[relative] = source.replace(old, new, 1)

    header = 'lib/moo/deferred_pipeline.hpp'
    edit(header, 'class DeferredPipeline', 'class StockDeferredBuffers;\n\nclass DeferredPipeline',
         'class StockDeferredBuffers;')
    edit(header, '    std::auto_ptr<SpeedTreeOptimizer> m_spt;',
         '    std::auto_ptr<SpeedTreeOptimizer> m_spt;\n'
         '    std::auto_ptr<StockDeferredBuffers> m_stockDeferredBuffers;')
    cpp = 'lib/moo/deferred_pipeline.cpp'
    edit(cpp, '#include "deferred_pipeline.hpp"',
         '#include "deferred_pipeline.hpp"\n#include "stock_deferred_buffers.hpp"',
         '#include "stock_deferred_buffers.hpp"')
    edit(cpp, '        m_spt(new SpeedTreeOptimizer())',
         '        m_spt(new SpeedTreeOptimizer()),\n'
         '        m_stockDeferredBuffers(new StockDeferredBuffers(*this))')
    edit(cpp, '    success &= m_lightsManager->init();',
         '    success &= m_lightsManager->init();\n'
         '    success &= m_stockDeferredBuffers->initialise();',
         '    success &= m_stockDeferredBuffers->initialise();')
    edit(cpp, 'void DeferredPipeline::begin()\n{\n    BW_GUARD;',
         'void DeferredPipeline::begin()\n{\n    BW_GUARD;\n'
         '    if (!m_stockDeferredBuffers->begin())\n'
         '        ERROR_MSG("Deferred buffers: sampled scene depth is unavailable\\n");',
         '    if (!m_stockDeferredBuffers->begin())')
    edit(cpp, 'void DeferredPipeline::end()\n{\n    BW_GUARD;',
         'void DeferredPipeline::end()\n{\n    BW_GUARD;\n'
         '    if (!m_stockDeferredBuffers->end())\n'
         '        ERROR_MSG("Deferred buffers: scene depth restoration failed\\n");',
         '    if (!m_stockDeferredBuffers->end())')
    edit(cpp, '    //-- save stencil state because it\'s used for optimization in underlying sub-systems.',
         '    // #1513 9c3d60: reconstruct depth, convert materials, then apply decals.\n'
         '    if (!m_stockDeferredBuffers->prepare())\n'
         '    {\n'
         '        ERROR_MSG("Deferred buffers: scene reconstruction failed\\n");\n'
         '        return;\n'
         '    }\n\n'
         '    //-- save stencil state because it\'s used for optimization in underlying sub-systems.',
         '    if (!m_stockDeferredBuffers->prepare())')
    edit(cpp, '            m_HDRSupport->setQualityOption(option);',
         '            m_HDRSupport->setQualityOption(option);\n'
         '            m_stockDeferredBuffers->setLightingQuality(option);',
         '            m_stockDeferredBuffers->setLightingQuality(option);')
    edit(cpp, '            m_SSAOSupport->setQualityOption(option);',
         '            m_SSAOSupport->setQualityOption(option);\n'
         '            m_SSAOSupport->enable(option < 3);',
         '            m_SSAOSupport->enable(option < 3);')
    edit(cpp, '            m_dynamicShadowManager->setQualityOption(option);',
         '            m_dynamicShadowManager->setQualityOption(option);\n'
         '            m_stockDeferredBuffers->setShadowQuality(option);',
         '            m_stockDeferredBuffers->setShadowQuality(option);')
    edit(cpp, '    m_SSAOSupport->resolve();',
         '    // SSAO/contact shadows were generated by the native DBE owner before decals.',
         '    // SSAO/contact shadows were generated by the native DBE owner before decals.')

    cpp = 'lib/moo/deferred_lights_manager.cpp'
    edit(cpp, '#include "deferred_lights_manager.hpp"',
         '#include "deferred_lights_manager.hpp"\n#include "stock_deferred_buffers.hpp"',
         '#include "stock_deferred_buffers.hpp"')
    current = pending.get(cpp,(root/cpp).read_text())
    if '    if (!drawStockDeferredSunLight(m_material))' not in current:
        start = current.index('void LightsManager::drawSunLight()')
        end = current.index('void LightsManager::drawSpots()',start)
        previous = current[start:end]
        replacement = '''void LightsManager::drawSunLight()
{
    BW_GUARD;
    if (!drawStockDeferredSunLight(m_material))
        ERROR_MSG("Deferred lighting: original SUN draw failed\\n");
}

//--------------------------------------------------------------------------------------------------
'''
        pending[cpp] = current[:start]+replacement+current[end:]

    cpp = 'lib/moo/deferred_decals_manager.cpp'
    edit(cpp, '#include "deferred_decals_manager.hpp"',
         '#include "deferred_decals_manager.hpp"\n#include "stock_deferred_buffers.hpp"',
         '#include "stock_deferred_buffers.hpp"')
    edit(cpp, '    //-- 4. set render targets.',
         '    if (!bindStockDeferredLegacyDecalInputs(effect))\n'
         '    {\n'
         '        ERROR_MSG("Deferred decals: original material inputs are unavailable\\n");\n'
         '        return;\n'
         '    }\n\n    //-- 4. set render targets.',
         '    if (!bindStockDeferredLegacyDecalInputs(effect))')
    edit(cpp, '        Moo::rc().setRenderTarget(1, Renderer::instance().pipeline()->gbufferSurface(1));',
         '        Moo::rc().setRenderTarget(2, Renderer::instance().pipeline()->gbufferSurface(0));\n'
         '        Moo::rc().setRenderTarget(1, Renderer::instance().pipeline()->gbufferSurface(1));',
         '        Moo::rc().setRenderTarget(2, Renderer::instance().pipeline()->gbufferSurface(0));')
    edit(cpp, 'void DecalsManager::deleteUnmanagedObjects()\n{\n    BW_GUARD;',
         'void DecalsManager::deleteUnmanagedObjects()\n{\n    BW_GUARD;\n'
         '    for (auto& material : m_materials) clearStockDeferredLegacyDecalInputs(material);\n'
         '    for (auto& material : m_debug_materials) clearStockDeferredLegacyDecalInputs(material);',
         '    for (auto& material : m_materials) clearStockDeferredLegacyDecalInputs(material);')

    cpp = 'lib/romp/ssao_support.cpp'
    edit(cpp, '#include "ssao_support.hpp"',
         '#include "ssao_support.hpp"\n#include "stock_deferred_buffers.hpp"',
         '#include "stock_deferred_buffers.hpp"')
    edit(cpp, 'SSAOParamsConstant(const SSAOSupport& ssao) : m_ssao(ssao)\n        {\n        }',
         'SSAOParamsConstant(const SSAOSupport& ssao) : m_ssao(ssao)\n'
         '        {\n            m_params.setZero();\n        }',
         '            m_params.setZero();')
    edit(cpp, '                m_params.row(0, Vector4(cfg.m_speedtree.x, cfg.m_speedtree.y, 0, 0));',
         '                const float configuredGamma=m_ssao.settings().m_terrainAOGammaCorrection;\n'
         '                const float terrainGamma=configuredGamma>=.25f ? (configuredGamma<1.f ? configuredGamma : 1.f) : .25f;\n'
         '                m_params.row(0, Vector4(cfg.m_speedtree.x, cfg.m_speedtree.y,\n'
         '                    m_ssao.settings().m_localLights,terrainGamma));',
         '                const float configuredGamma=m_ssao.settings().m_terrainAOGammaCorrection;')
    edit(cpp, '            pEffect->SetMatrix(constantHandle, &m_params);\n            return true;',
         '            return SUCCEEDED(pEffect->SetMatrix(constantHandle, &m_params));')
    edit(cpp, '                effect->SetTexture("g_depth", m_rtDownsampledDepth->pTexture());',
         '                effect->SetTexture("g_depth", m_rtDownsampledDepth->pTexture());\n'
         '                if (!setStockDeferredTextureScale(effect,"stockDepthUVScale",\n'
         '                    m_rtDownsampledDepth->width(),m_rtDownsampledDepth->height()))\n'
         '                {\n'
         '                    m_rt->pop();\n'
         '                    ERROR_MSG("SSAO: source depth coordinates could not be assigned\\n");\n'
         '                    return;\n'
         '                }',
         '                if (!setStockDeferredTextureScale(effect,"stockDepthUVScale",')
    for source,target in (('m_rt','m_rtBlure'),('m_rtBlure','m_rt')):
        anchor = '            effect->SetTexture("g_srcMap", ' + source + '->pTexture());'
        edit(cpp, anchor, anchor + '\n'
             '            if (!setStockDeferredTextureScale(effect,"stockSourceUVScale",\n'
             '                ' + source + '->width(),' + source + '->height()))\n'
             '            {\n'
             '                ' + target + '->pop();\n'
             '                ERROR_MSG("SSAO: blur source coordinates could not be assigned\\n");\n'
             '                return;\n'
             '            }',
             '                ' + source + '->width(),' + source + '->height()))')

    header = 'lib/romp/ssao_settings.hpp'
    edit(header, 'm_speedtree(1.0f, 0.0f), m_terrain', 'm_speedtree(1.0f, 1.0f), m_terrain')
    edit(header, '\tInfluenceFactors\tm_influences;',
         '\tInfluenceFactors\tm_influences;\n'
         '\tfloat m_localLights = .75f;\n'
         '\tfloat m_terrainAOGammaCorrection = 1.f;', 'float m_localLights = .75f;')
    cpp = 'lib/romp/ssao_settings.cpp'
    edit(cpp, 'm_radius(0.04f)', 'm_radius(0.1f)')
    edit(cpp, 'm_fade(3.f)', 'm_fade(2.f)')
    edit(cpp, 'readFloat("redius", m_radius)', 'readFloat("radius", m_radius)')
    edit(cpp, 'readFloat("fade", m_fade)', 'readFloat("fadeNear", m_fade)')
    edit(cpp, '    m_fade    = iData->readFloat("fadeNear", m_fade);',
         '    m_fade    = iData->readFloat("fadeNear", m_fade);\n'
         '    m_localLights = iData->readFloat("influences/localLights", m_localLights);\n'
         '    m_terrainAOGammaCorrection = iData->readFloat("terrainAOGammaCorrection", m_terrainAOGammaCorrection);',
         '    m_localLights = iData->readFloat("influences/localLights", m_localLights);')
    edit(cpp, 'writeFloat("redius", m_radius)', 'writeFloat("radius", m_radius)')
    edit(cpp, 'writeFloat("fade", m_fade)', 'writeFloat("fadeNear", m_fade)')
    edit(cpp, '    oData->writeFloat("fadeNear", m_fade);',
         '    oData->writeFloat("fadeNear", m_fade);\n'
         '    oData->writeFloat("influences/localLights", m_localLights);\n'
         '    oData->writeFloat("terrainAOGammaCorrection", m_terrainAOGammaCorrection);',
         '    oData->writeFloat("influences/localLights", m_localLights);')

    header = 'lib/romp/enviro_minder.hpp'
    edit(header, '#define ENVIRO_MINDER_HPP',
         '#define ENVIRO_MINDER_HPP\n#include "stock_deferred_buffers.hpp"',
         '#include "stock_deferred_buffers.hpp"')
    edit(header, '    void loadHDR(const DataSectionPtr& data, bool loadFromExternal);',
         '    wot::StockDeferredMaterialSettings stockDeferredMaterialSettings_;\n'
         '    wot::StockScreenSpaceShadowSettings stockScreenSpaceShadowSettings_;\n'
         '    void loadStockDeferredMaterials(const DataSectionPtr& data, bool loadFromExternal);\n'
         '    void loadHDR(const DataSectionPtr& data, bool loadFromExternal);',
         '    wot::StockDeferredMaterialSettings stockDeferredMaterialSettings_;')
    cpp = 'lib/romp/enviro_minder.cpp'
    edit(cpp, '        loadTimeOfDay(pDS, loadFromExternal);',
         '        loadTimeOfDay(pDS, loadFromExternal);\n'
         '        loadStockDeferredMaterials(pDS, loadFromExternal);',
         '        loadStockDeferredMaterials(pDS, loadFromExternal);')
    edit(cpp, '    s_activatedEM_ = this;',
         '    s_activatedEM_ = this;\n'
         '    activateStockDeferredMaterialSettings(stockDeferredMaterialSettings_);\n'
         '    activateStockScreenSpaceShadowSettings(stockScreenSpaceShadowSettings_);',
         '    activateStockDeferredMaterialSettings(stockDeferredMaterialSettings_);')
    edit(cpp, '    s_activatedEM_ = NULL;',
         '    activateStockDeferredMaterialSettings(wot::StockDeferredMaterialSettings());\n'
         '    activateStockScreenSpaceShadowSettings(wot::StockScreenSpaceShadowSettings());\n'
         '    s_activatedEM_ = NULL;',
         '    activateStockDeferredMaterialSettings(wot::StockDeferredMaterialSettings());')
    edit(cpp, 'void EnviroMinder::loadHDR(const DataSectionPtr& data, bool loadFromExternal)',
         READER + 'void EnviroMinder::loadHDR(const DataSectionPtr& data, bool loadFromExternal)',
         'void EnviroMinder::loadStockDeferredMaterials(')

    application = Path(__file__).resolve().parent
    headers = ((application / 'stock_deferred_buffers.hpp', root / 'lib/stock_deferred_buffers.hpp'),
               (application.parent / 'include/wot/stock_deferred_buffers.hpp',
                root / 'lib/wot/stock_deferred_buffers.hpp'))
    sources = [(destination, source.read_text()) for source, destination in headers]
    for relative, text in pending.items():
        (root / relative).write_text(text)
    for destination, text in sources:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text)


def patch_resources(root):
    root = Path(root)
    pending = {}

    def edit(relative, old, new, present=None):
        text = pending.get(relative)
        if text is None:
            text = (root / relative).read_text(encoding='latin1')
        if (present or new) in text:
            return
        if text.count(old) != 1:
            raise ValueError('Deferred resource layout anchor changed: ' + relative + ': ' + repr(old))
        pending[relative] = text.replace(old, new, 1)

    writer = 'shaders/std_effects/write_g_buffer.fxh'
    edit(writer, 'o.color1.rg = cartesianToSpherical(nn);', 'o.color1.rgb = nn * .5f + .5f;')
    edit(writer, 'o.color1.rg = packedNormal;',
         'o.color1.rgb = sphericalToCartesian(packedNormal) * .5f + .5f;')
    edit(writer, 'o.color1.b = amount;', 'o.color0.g = amount;')
    edit(writer, 'o.color0.rgb = packFloatToVec3(depth * g_farPlane.y);',
         '// Scene depth is rasterised into the sampled INTZ depth owner.\n'
         '\to.color2.a = 1.f / 255.f;')
    edit(writer, 'void g_buffer_writeDepth(inout G_BUFFER_LAYOUT o, in float depth)',
         'void g_buffer_markLegacyMaterial(inout G_BUFFER_LAYOUT o)')
    edit(writer, '\to.color0.a = id * invByte;',
         '\tif (id != G_OBJECT_KIND_TERRAIN)\n'
         '\t{\n\t\to.color0.r = .04f;\n\t\to.color0.b = 0.f;\n\t}\n'
         '\to.color0.a = id * invByte;', 'if (id != G_OBJECT_KIND_TERRAIN)')
    # Terrain has a different reviewed source layout: specular alpha in R and
    # fixed .1 in G (original terrain2 DX9 Color PS67). Its authored AO and
    # shadow alpha remain untouched, including multipass blending.
    for name, amount in (('terrain2.fx', 'diffColor.w'), ('terrain2_lod_texture.fx', 'diffuseColor.a')):
        terrain = 'shaders/terrain/' + name
        edit(terrain, 'g_buffer_writeSpecAmount(o, ' + amount + ');',
             'o.color0.rgb = float3(' + amount + ', .1f, 0.f);')
    edit('shaders/terrain/terrain2.fx', 'o.color1.rg *= normal.w;', 'o.color1.rgb *= normal.w;')

    reader = 'shaders/std_effects/read_g_buffer.fxh'
    edit(reader, '#include "nv_stereo.fxh"', '''#include "nv_stereo.fxh"
// The modern colour channels contain material parameters, never packed depth.
texture stockLinearDepthMap : HierarchicalZMap;
float4 stockSceneDRR : DRRParams;
sampler stockLinearDepthSampler = sampler_state
{
    Texture = (stockLinearDepthMap);
    MINFILTER = POINT; MAGFILTER = POINT; MIPFILTER = NONE;
    ADDRESSU = CLAMP; ADDRESSV = CLAMP;
};''', 'texture stockLinearDepthMap : HierarchicalZMap;')
    text = pending.get(reader, (root / reader).read_text(encoding='latin1'))
    text = text.replace('unpackFloatFromVec3(tex2D(g_GBufferChannel0Sml, uv).rgb)',
                        'tex2D(stockLinearDepthSampler, uv).r')
    # Public fullscreen passes pass logical 0..1 UVs. Textures retain their
    # full allocation and only the DRR rectangle contains scene pixels.
    text = text.replace('stockLinearDepthSampler, uv)', 'stockLinearDepthSampler, uv * stockSceneDRR.xy)')
    text = re.sub(r'(g_GBufferChannel[012]Sml, )uv\)', r'\1uv * stockSceneDRR.xy)', text)
    pending[reader] = text
    edit(reader, 'half2 enc = tex2D(g_GBufferChannel1Sml, uv * stockSceneDRR.xy).rg;\n    return sphericalToCartesian(enc);',
         'return tex2D(g_GBufferChannel1Sml, uv * stockSceneDRR.xy).rgb * 2.f - 1.f;')
    edit(reader, 'return tex2D(g_GBufferChannel1Sml, uv * stockSceneDRR.xy).b;',
         'return tex2D(g_GBufferChannel0Sml, uv * stockSceneDRR.xy).g;')
    # VPOS consumers start with physical allocation UVs. Convert only their
    # GBuffer input, leaving water reflection/refraction coordinates untouched.
    edit('shaders/water/water.fx', 'g_buffer_readWorldPos(screenUV)',
         'g_buffer_readWorldPos(screenUV / stockSceneDRR.xy)')
    edit('shaders/water/water.fx', 'g_buffer_readLinearZ( screenUV )',
         'g_buffer_readLinearZ( screenUV / stockSceneDRR.xy )')
    lighting = 'shaders/std_effects/resolve_lighting.fx'
    text = (root / lighting).read_text(encoding='latin1')
    text = text.replace('screenXY = SC2TC(vPos);', 'screenXY = SC2TC(vPos) / stockSceneDRR.xy;')
    pending[lighting] = text

    ssao = 'shaders/ssao/ssao.fx'
    edit(ssao, 'texture g_depth;', 'texture g_depth;\nfloat2 stockDepthUVScale = float2(1.f,1.f);',
         'float2 stockDepthUVScale = float2(1.f,1.f);')
    text = pending.get(ssao,(root/ssao).read_text(encoding='latin1'))
    text = re.sub(r'tex2D\(g_depthSampler, (i.tc(?: \+ s[0-3].xy)?)\)',
                  r'tex2D(g_depthSampler, (\1) * stockDepthUVScale)',text)
    pending[ssao] = text
    blur = 'shaders/ssao/blure4x4.fx'
    edit(blur, 'texture g_srcMap;', 'texture g_srcMap;\nfloat2 stockSourceUVScale = float2(1.f,1.f);',
         'float2 stockSourceUVScale = float2(1.f,1.f);')
    edit(blur, 'tex2D(g_srcMapSampler, i.tc + g_invScreen.zw * off)',
         'tex2D(g_srcMapSampler, i.tc * stockSourceUVScale + g_invScreen.zw * off)')

    decal = 'shaders/std_effects/deferred_decal.fx'
    text = (root / decal).read_text(encoding='latin1')
    if '#include "stock_deferred_legacy_decal.fxh"' not in text:
        # This resource only writes albedo/normal today. Extend both actual
        # normal-map techniques with the real legacy material conversion.
        text = '#include "stock_deferred_legacy_decal.fxh"\n' + text
        text = text.replace('float4 color1 : COLOR1;', 'float4 color1 : COLOR1;\n\tfloat4 material : COLOR2;')
        text = text.replace('g_buffer_readObjectKind(screenXY)',
                            'tex2D(stockDecalObjectKindsSampler, screenXY * stockSceneDRR.xy).a * 255.f')
        text = text.replace('screenXY = SC2TC(vPos);', 'screenXY = SC2TC(vPos) / stockSceneDRR.xy;')
        text = text.replace('float3 oNormal = float3(cartesianToSpherical(normalize(mul(nn, TBN))), map2Src.w);',
                            'float3 oNormal = normalize(mul(nn, TBN)) * .5f + .5f;')
        text = text.replace('float3 oNormal = float3(cartesianToSpherical(normalize(mul(nn, TBN))), 0);',
                            'float3 oNormal = normalize(mul(nn, TBN)) * .5f + .5f;')
        text = text.replace('float3 nn\t   = (tex2D(g_atlasMapSml, newAtlas2UV).xyz * 2.0f) - 1.0f;',
                            'float4 normalSource = tex2D(g_atlasMapSml, newAtlas2UV);\n'
                            '\tfloat3 nn = normalSource.xyz * 2.f - 1.f;')
        for function, gloss in (('PS_BUMP', 'map2Src.w'), ('PS_PARALLAX', 'normalSource.w')):
            start = text.index('DECAL_PS_OUT_TWO_RT ' + function + '(')
            end = text.index('\n}', start)
            body = text[start:end]
            old = '\to.color0 = float4(oColor.xyz, alpha);'
            if body.count(old) != 1:
                raise ValueError('Deferred legacy decal output changed: ' + function)
            body = body.replace(old,
                '\tfloat3 material;\n\tstockConvertLegacyDecal(oColor.xyz, ' + gloss + ', material);\n'
                '\to.material = float4(material, alpha);\n' + old)
            text = text[:start] + body + text[end:]
        # Every pass declares the third target's mask. Only BUMP/PARALLAX
        # write its material colour; stencil/debug/diffuse preserve it.
        text = re.sub(r'(COLORWRITEENABLE1\s*=\s*[^;]+;)', r'\1\n\t\tCOLORWRITEENABLE2 = 0x00;', text)
        for technique in ('BUMP', 'PARALLAX'):
            start = text.index('technique ' + technique + '\n')
            end = text.index('\n}', start)
            body = text[start:end].replace('COLORWRITEENABLE2 = 0x00;', 'COLORWRITEENABLE2 = 0x07;')
            text = text[:start] + body + text[end:]
        if 'cartesianToSpherical(normalize(mul(nn, TBN)))' in text or 'normalSource' not in text:
            raise ValueError('Deferred legacy decal normal source changed')
        pending[decal] = text
    legacy = Path(__file__).with_name('stock_deferred_legacy_decal.fxh').read_text()
    # Geometry already writes real depth through rasterisation. Preserve a
    # named material marker operation rather than a no-op depth writer API.
    for path in (root / 'shaders').rglob('*'):
        if path.suffix not in ('.fx', '.fxh'):
            continue
        relative = path.relative_to(root).as_posix()
        if relative in pending:
            text = pending[relative]
        else:
            data = path.read_bytes()
            if (b'g_buffer_writeDepth(o, ' not in data and
                    b'g_buffer_writeObjectKind(o, g_objectID ?' not in data):
                continue
            text = data.decode('latin1')
        replaced = re.sub(r'g_buffer_writeDepth\(o, [^;]+\);',
                          'g_buffer_markLegacyMaterial(o);', text)
        # Original lightonly/normalmap COLOR shaders encode the double-sided
        # flag in bit 7 as well as the base static/dynamic kind (4/5).
        replaced = replaced.replace(
            'g_buffer_writeObjectKind(o, g_objectID ? G_OBJECT_KIND_DYNAMIC : G_OBJECT_KIND_STATIC);',
            'g_buffer_writeObjectKind(o, (g_objectID ? G_OBJECT_KIND_DYNAMIC : G_OBJECT_KIND_STATIC) + (doubleSided ? 128 : 0));')
        if replaced != text:
            pending[relative] = replaced
    for relative, text in pending.items():
        (root / relative).write_text(text,encoding='latin1')
    (root / 'shaders/std_effects/stock_deferred_legacy_decal.fxh').write_text(legacy)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('engine_root', type=Path)
    parser.add_argument('--resources', type=Path)
    args = parser.parse_args()
    apply(args.engine_root)
    if args.resources:
        patch_resources(args.resources)
