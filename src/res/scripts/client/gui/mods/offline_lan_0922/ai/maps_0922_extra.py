"""Coarse #1513-only tactical annotations.

Routes below are *minimap/bounds coarse lanes*, not precise spawn or obstacle
traces. Exact objectives and team starts are decoded independently from the
pinned #1513 arena data by the navigation baker. These lane sketches
deliberately stay away from map edges and are for validated route projection
and the driver's local probes.
"""


def _route(name, points, risk, roles):
    return {'id': name, 'capacity': 5, 'risk': risk,
            'role_weights': roles, 'waypoints': tuple(points)}


def _weights(brawler, support, flanker, sniper, scout):
    return {'brawler': brawler, 'support': support, 'flanker': flanker,
            'sniper': sniper, 'scout': scout, 'artillery': 0.0}


def _map(name, bounds, lanes):
    """Lanes are individually traced coarse coordinates, mirrored for team 2."""
    south = []
    north = []
    for lane_id, points, risk, roles in lanes:
        south.append(_route(lane_id, points, risk, roles))
        north.append(_route(lane_id, tuple(reversed(points)), risk, roles))
    return {'name': name, 'bounds': bounds,
            'routes': {1: tuple(south), 2: tuple(north)},
            'annotation_confidence': 'coarse-minimap-bounds'}


